"""Writes visuals/avatar_specs.gd from the human model constants (run by build_humans.py, or on its own)."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
from human_model import Human, KIND


def spec_for(kind):
    h = Human(kind)
    D = h.D
    return {
        "height": h.H, "crown": float(h.crown_y), "hat_y": float(h.crown_y - 0.075 * (h.hh / 0.232)),
        "hat_scale": D["hat_scale"], "pack": D["pack"], "pack_scale": D["pack_scale"],
        "head_w": h.hw, "ponytail": h.hair_style == "ponytail", "eye_y": float(h.eye_y),
    }


def main():
    lines = ["extends RefCounted", "class_name AvatarSpecs", "",
             "## GENERATED by tools/assetgen/gen_specs.py - do not edit by hand.",
             "## Per-model constants (metres above the feet, rig space) used to place hats, the backpack and the name tag.", "",
             "const SPECS := {"]
    for kind in ("boy", "girl", "man", "woman"):
        s = spec_for(kind)
        p = s["pack"]
        lines.append('    "%s": {"height": %.3f, "crown": %.3f, "hat_y": %.3f, "hat_scale": %.2f, "pack": Vector3(%.3f, %.3f, %.3f), "pack_scale": %.2f, "head_w": %.3f, "ponytail": %s, "eye_y": %.3f},'
                     % (kind, s["height"], s["crown"], s["hat_y"], s["hat_scale"], p[0], p[1], p[2], s["pack_scale"], s["head_w"], str(s["ponytail"]).lower(), s["eye_y"]))
    lines += ["}", "", "static func get_spec(kind: String) -> Dictionary:", "    return SPECS.get(kind, SPECS[\"man\"])", ""]
    out = os.path.join(ROOT, "visuals", "avatar_specs.gd")
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
